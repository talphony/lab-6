package com.example.fbs.orderprocessing.model;

/** Статусы заказа в рамках блока A3. Сборка и отгрузка (A4, A5) добавят свои. */
public enum OrderStatus {
    /** Загружен, резерв ещё не ставили. */
    NEW,
    /** Товар зарезервирован, выдано задание на сборку. */
    RESERVED,
    /** Не хватило свободного остатка: проблемный заказ для менеджера. */
    NOT_ENOUGH_STOCK,
    /** Отменён, резерв снят. */
    CANCELLED
}
